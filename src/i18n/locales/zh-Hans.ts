/**
 * zh-Hans.ts — Simplified Chinese.
 *
 * The `zh` alias resolves here rather than to Traditional, because a browser sending a
 * bare `zh` is overwhelmingly sending Simplified, and because the Chinese readers this
 * package sits next to Bahasa Melayu for — Malaysia and Singapore — read Simplified.
 * `zh-Hant` is a separate pack; the two scripts are not mutually readable, so neither
 * falls back to the other.
 *
 * Notes on a few choices, so a later editor does not "fix" them back:
 *
 *  - Typeface names (`Georgia`, `Arial`) and CSS property names are absent on purpose.
 *    They are identifiers, not words — see the `i18n` module header.
 *  - `Rule` is 分隔线, the horizontal line, not 规则. Both are correct English readings
 *    of the word; only one is what the button inserts.
 *  - `Scrim` has no settled Chinese term; 遮罩 (the overlay that makes text legible over
 *    a photo) is what the property actually does.
 *
 * @module i18n/locales/zh-Hans
 */

